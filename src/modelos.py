
"""Validated data structures shared by the medication-review components."""

from typing import Literal

from pydantic import BaseModel, Field, model_validator


class Fragment(BaseModel):
    """One text fragment from an official CIMA technical-sheet section."""

    nregistro: str = Field(min_length=1)
    nombre: str | None = None
    seccion: str = Field(min_length=1)
    titulo: str | None = None
    texto: str = Field(min_length=1)


class Citation(BaseModel):
    """An exact quotation linked to a CIMA medicine and section."""

    nregistro: str = Field(min_length=1)
    seccion: str = Field(min_length=1)
    literal_quote: str = Field(min_length=1)


class Finding(BaseModel):
    """One issue or warning to show in the medication-review report."""

    tipo: Literal["duplicado", "advertencia_atc", "interaccion", "cascada"]
    descripcion: str = Field(min_length=1)
    cita: Citation | None = None
    pregunta_medico: str | None = None


class Medication(BaseModel):
    """A medicine in one fictional patient's medication list."""

    nregistro: str = Field(min_length=1)
    nombre: str = Field(min_length=1)
    dosis: str = Field(min_length=1)
    prescriptor: str = Field(min_length=1)


class Patient(BaseModel):
    """A fictional patient used for development or evaluation."""

    id: str = Field(min_length=1)
    edad: int = Field(ge=0, le=120)
    grupo: Literal["desarrollo", "evaluacion"]
    medicamentos: list[Medication] = Field(min_length=1)


class CascadeMedication(BaseModel):
    """A medicine or class selected by ingredient codes, ATC prefixes, or both.

    When both lists are supplied, both must match the same medicine.
    ATC exclusions take precedence. Matching is implemented in the rules engine.
    """

    model_config = {"extra": "forbid"}

    nombre: str = Field(min_length=1)
    cod_principio_activo: list[str] = Field(default_factory=list)
    cod_atc: list[str] = Field(default_factory=list)
    atc_excluidos: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_codes(self):
        """Require usable matching codes rather than matching by name."""
        if not self.cod_principio_activo and not self.cod_atc:
            raise ValueError("Provide ingredient codes, ATC codes, or both.")
        for code in self.cod_principio_activo + self.cod_atc + self.atc_excluidos:
            if not code.strip() or code != code.strip():
                raise ValueError("Codes cannot be empty or contain surrounding spaces.")
        return self


class CascadeSource(BaseModel):
    """A contributor-supplied reference, not proof of clinical validation."""

    model_config = {"extra": "forbid"}

    cita: str = Field(min_length=1)
    pmid: str | None = None
    doi: str | None = None
    url: str | None = None


class CascadeCase(BaseModel):
    """A possible prescribing cascade for review, with an optional source list."""

    model_config = {"extra": "forbid"}

    id: str = Field(pattern=r"^C\d{2}$")
    medicamento_causante: CascadeMedication
    efecto_adverso: str = Field(min_length=1)
    medicamento_cascada: CascadeMedication
    fuente: list[CascadeSource] | None = None
    pregunta_medico: str = Field(min_length=1)
    estado: Literal["hipotesis_a_revisar"] = "hipotesis_a_revisar"
    hipotesis: str | None = None
    nota: str | None = None
    caso_prueba: str | None = None
    ejemplos: list[str] = Field(default_factory=list)



class StructuredOutputRAG(BaseModel):
    """Validated response generated by the RAG language model."""

    status: Literal["found", "not_found"]
    description: str = Field(min_length=1)
    citations: list[Citation]

    @model_validator(mode="after")
    def validate_citations(self):
        """Require citations for findings and none when evidence is missing."""

        if self.status == "found" and not self.citations:
            raise ValueError("A found response requires citations.")

        if self.status == "not_found" and self.citations:
            raise ValueError("A not_found response cannot have citations.")

        return self
